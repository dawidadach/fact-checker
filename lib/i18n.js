export const UI_LANGS = ["pl", "en"];
let LANG = "en";

export function browserLang() {
  const ui = (globalThis.chrome?.i18n?.getUILanguage?.() || globalThis.navigator?.language || "en").toLowerCase();
  return ui.startsWith("pl") ? "pl" : "en";
}
// pref: "auto" | "pl" | "en"
export function resolveLang(pref) {
  return UI_LANGS.includes(pref) ? pref : browserLang();
}
export function setLang(lang) {
  LANG = UI_LANGS.includes(lang) ? lang : "en";
  if (globalThis.document) document.documentElement.lang = LANG;
  return LANG;
}
export const getLang = () => LANG;

// Ustawia język na podstawie zapisanych ustawień (działa też w service workerze).
export async function initLang() {
  let pref = "auto";
  try { pref = (await chrome.storage.local.get("settings")).settings?.uiLang || "auto"; } catch { /* poza wtyczką */ }
  return setLang(resolveLang(pref));
}

export function t(key, vars = {}) {
  const s = DICT[LANG]?.[key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// data-i18n → textContent, data-i18n-html → innerHTML (tylko nasze stałe teksty),
// data-i18n-placeholder / -title / -aria → atrybuty.
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
}

